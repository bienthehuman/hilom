using System.Reflection;
using Hilom.Infrastructure.Modules;
using Hilom.SharedKernel.Domain;
using Microsoft.EntityFrameworkCore;

namespace Hilom.Infrastructure.Persistence;

/// <summary>
/// The single database context. Each module contributes its entity configurations, and its tables
/// land in the module's own PostgreSQL schema. See docs/adr/0001-modular-monolith.md.
/// </summary>
public sealed class AppDbContext(DbContextOptions<AppDbContext> options, ModuleRegistry modules) : DbContext(options)
{
    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.HasPostgresExtension("citext");
        modelBuilder.HasPostgresExtension("btree_gist");

        foreach (var module in modules.Modules.Where(m => HasEntityConfigurations(m.Assembly)))
        {
            modelBuilder.ApplyConfigurationsFromAssembly(module.Assembly);
        }

        ApplyConventions(modelBuilder, modules);
    }

    private static bool HasEntityConfigurations(Assembly assembly) =>
        assembly.GetTypes().Any(type => !type.IsAbstract && type.GetInterfaces().Any(i =>
            i.IsGenericType && i.GetGenericTypeDefinition() == typeof(IEntityTypeConfiguration<>)));

    /// <summary>Rules every table follows, so module configurations don't repeat them.</summary>
    internal static void ApplyConventions(ModelBuilder modelBuilder, ModuleRegistry modules)
    {
        foreach (var entityType in modelBuilder.Model.GetEntityTypes().ToList())
        {
            // Tables default to their module's schema (owned types with their own table included).
            var module = modules.FindByAssembly(entityType.ClrType.Assembly);
            if (module is not null && entityType.GetSchema() is null)
            {
                entityType.SetSchema(module.Schema);
            }

            if (entityType.IsOwned())
            {
                continue;
            }

            // Ids are generated by the app (UUID v7); Version maps to PostgreSQL xmin.
            if (typeof(Entity).IsAssignableFrom(entityType.ClrType) && entityType.BaseType is null)
            {
                var builder = modelBuilder.Entity(entityType.ClrType);
                builder.HasKey(nameof(Entity.Id));
                builder.Property(nameof(Entity.Id)).ValueGeneratedNever();
                builder.Property(nameof(Entity.Version)).IsRowVersion();
            }
        }
    }
}
